"""
Reads the RoiSet.zip generated by Medidas_MotherMachine.ijm and converts it into a
DataFrame with one row per measurement (channel, slice, time, length).

Usage in a notebook:
    from leer_roiset import leer_roiset, leer_muertes
    df = leer_roiset('01-25092026-stack_RoiSet.zip')
    muertes = leer_muertes('01-25092026-stack_RoiSet.zip')   # channel, slice, time of death

Usage from the terminal (saves a CSV next to the zip):
    python leer_roiset.py 01-25092026-stack_RoiSet.zip

Requires: pip install roifile pandas numpy
"""
import re
import struct
import sys
import warnings
import zipfile
from pathlib import Path

import numpy as np
import pandas as pd
import roifile

# Name set by the macro: C05_s023 (measurement), C05_s023_NA (not measurable), C05_s023_MUERTE (death)
PATRON_NOMBRE = re.compile(r'^C(\d+)_s(\d+)(?:_(NA|MUERTE))?$')
ESTADOS = {None: 'medida', 'NA': 'NA', 'MUERTE': 'muerte'}
# Slice label: 01_260925_103936_Regrowth_...  ->  date YYMMDD, time HHMMSS
PATRON_HORA = re.compile(r'_(\d{6})_(\d{6})_')


def _hora_de_etiqueta(etiqueta):
    m = PATRON_HORA.search(etiqueta or '')
    if not m:
        return pd.NaT
    return pd.to_datetime(m.group(1) + m.group(2), format='%y%m%d%H%M%S')


def _longitud_px(coords):
    coords = np.asarray(coords, dtype=float)
    if len(coords) < 2:
        return np.nan
    return float(np.sum(np.hypot(*np.diff(coords, axis=0).T)))


def _props_crudas(datos):
    """
    Properties text of a .roi read directly from the file.
    (roifile truncates the last characters of the properties, so it is not used for this.)
    ImageJ format: the offset of header 2 is in bytes 60-63; within it, the
    offset and length (in UTF-16 characters) of the properties are in bytes 40-47.
    """
    try:
        hdr2 = struct.unpack('>i', datos[60:64])[0]
        if hdr2 <= 0 or hdr2 + 48 > len(datos):
            return ''
        off, n = struct.unpack('>ii', datos[hdr2 + 40:hdr2 + 48])
        if off <= 0 or n <= 0:
            return ''
        return datos[off:off + 2 * n].decode('utf-16-be', errors='replace')
    except struct.error:
        return ''


def _leer_rois(ruta):
    """List of (roi, properties_text) from a RoiSet.zip or from a single .roi."""
    ruta = Path(ruta)
    if zipfile.is_zipfile(ruta):
        with zipfile.ZipFile(ruta) as z:
            datos = [z.read(n) for n in z.namelist() if n.lower().endswith('.roi')]
    else:
        datos = [ruta.read_bytes()]
    return [(roifile.ImagejRoi.frombytes(d), _props_crudas(d)) for d in datos]


def _propiedades(texto):
    """The properties saved by the macro (text 'key: value' per line) -> dict."""
    props = {}
    for linea in (texto or '').splitlines():
        if ':' in linea:
            k, v = linea.split(':', 1)
            props[k.strip()] = v.strip()
    return props


def _tabla_completa(ruta_zip):
    """All the macro ROIs (measurements, NA and deaths) with their consistency checks."""
    ruta_zip = Path(ruta_zip)
    filas, problemas = [], []
    for roi, texto_props in _leer_rois(ruta_zip):
        m = PATRON_NOMBRE.match(roi.name or '')
        if not m:
            problemas.append(f'ROI without a valid name (added with [t]?): "{roi.name}"')
            continue
        canal, slice_nombre, estado = int(m.group(1)), int(m.group(2)), ESTADOS[m.group(3)]
        props = _propiedades(texto_props)

        if roi.position and roi.position != slice_nombre:
            problemas.append(f'{roi.name}: the name says slice {slice_nombre} '
                             f'but the ROI is in slice {roi.position}')

        coords = roi.coordinates()
        etiqueta = props.get('etiqueta_slice', '')
        filas.append({
            'canal': canal,
            'slice': slice_nombre,
            'fecha_hora': _hora_de_etiqueta(etiqueta),
            'longitud_px': _longitud_px(coords) if estado == 'medida' else np.nan,
            'estado': estado,
            'x_ini': coords[0][0], 'y_ini': coords[0][1],
            'x_fin': coords[-1][0], 'y_fin': coords[-1][1],
            'coordenadas': np.round(np.asarray(coords, dtype=float), 2).tolist(),   # all the points [[x, y], ...]
            'etiqueta_slice': etiqueta,
            'imagen': props.get('imagen', ''),
            'stack_pareja': props.get('stack_pareja', ''),
            'tipo_muerte': props.get('tipo_muerte', ''),
            'nota': props.get('nota', ''),
            'medido_el': pd.to_datetime(props.get('medido_el'), errors='coerce'),
            'roi': roi.name,
        })

    df = pd.DataFrame(filas)
    if df.empty:
        warnings.warn(f'No valid measurements in {ruta_zip.name}')
        return df

    # --- traceability checks ---
    dup = df[df.duplicated(['canal', 'slice', 'estado'], keep=False)]
    if not dup.empty:
        problemas.append('Repeated channel/slice: ' + ', '.join(sorted(dup['roi'])))
    varias = df[df.estado == 'muerte'].groupby('canal').size()
    if (varias > 1).any():
        problemas.append(f'Channels with more than one marked death: {varias[varias > 1].index.tolist()}')
    if df['fecha_hora'].isna().any():
        problemas.append(f'{df.fecha_hora.isna().sum()} measurements without a time in the slice label')
    if df['imagen'].nunique() > 1:
        problemas.append('The zip mixes measurements from several images: ' + ', '.join(df.imagen.unique()))
    for p in problemas:
        warnings.warn(p)
    return df


def _t0(df, t0):
    """Time origin: the given one or the first image with a measurement."""
    if t0 is not None:
        return pd.Timestamp(t0)
    return df.loc[df.estado == 'medida', 'fecha_hora'].min()


def leer_roiset(ruta_zip, um_por_px=None, incluir_na=False, t0=None):
    """
    Parameters
    ----------
    ruta_zip   : path to the *_RoiSet.zip
    um_por_px  : pixel size (µm/px). If given, adds the column 'longitud_um'.
    incluir_na : if True, also includes the slices marked NA (length = NaN).
    t0         : reference instant for 'tiempo_min'. By default, the time of the
                 first measured image in the zip (the lowest slice).

    Returns a DataFrame (one row per measurement) sorted by channel and time.
    Deaths marked with the macro are read with leer_muertes().
    """
    df = _tabla_completa(ruta_zip)
    if df.empty:
        return df
    t0 = _t0(df, t0)
    df = df[df['estado'].isin(['medida', 'NA'] if incluir_na else ['medida'])].copy()
    df = df.drop(columns=['tipo_muerte', 'nota'])

    df['tiempo_min'] = (df['fecha_hora'] - t0).dt.total_seconds() / 60
    if um_por_px is not None:
        df['longitud_um'] = df['longitud_px'] * um_por_px

    columnas = ['canal', 'slice', 'fecha_hora', 'tiempo_min', 'longitud_px']
    if um_por_px is not None:
        columnas.append('longitud_um')
    resto = [c for c in df.columns if c not in columnas]
    return (df[columnas + resto]
            .sort_values(['canal', 'slice'])
            .reset_index(drop=True))


def leer_muertes(ruta_zip, t0=None):
    """
    Deaths marked with key [6] in the macro: one row per channel with
    canal, slice, fecha_hora, tiempo_min (same origin as leer_roiset), tipo_muerte, nota.
    """
    df = _tabla_completa(ruta_zip)
    columnas = ['canal', 'slice', 'fecha_hora', 'tiempo_min', 'tipo_muerte', 'nota', 'x_ini', 'y_ini', 'roi']
    if df.empty or not (df.estado == 'muerte').any():
        return pd.DataFrame(columns=columnas)
    t0 = _t0(df, t0)
    m = df[df.estado == 'muerte'].copy()
    m['tiempo_min'] = (m['fecha_hora'] - t0).dt.total_seconds() / 60
    return m[columnas].sort_values('canal').reset_index(drop=True)


# Only when run from the terminal. Inside Jupyter __name__ is also
# '__main__' and sys.argv contains the kernel arguments, so it is skipped.
if __name__ == '__main__' and 'ipykernel' not in sys.modules:
    if len(sys.argv) < 2:
        sys.exit('Usage: python leer_roiset.py <RoiSet.zip> [um_por_px]')
    zip_path = Path(sys.argv[1])
    px = float(sys.argv[2]) if len(sys.argv) > 2 else None
    tabla = leer_roiset(zip_path, um_por_px=px)
    salida = zip_path.with_name(zip_path.stem.replace('_RoiSet', '') + '_medidas.csv')
    tabla.to_csv(salida, index=False)
    print(tabla.groupby('canal').size().rename('medidas').to_string())
    print(f'Saved: {salida}')
